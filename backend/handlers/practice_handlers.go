func reverseString(s string) string {
	r := []rune(s)
	for i, j := 0, len(r)-1; i < j; i, j = i+1, j-1 {
		r[i], r[j] = r[j], r[i]
	}
	return string(r)
}

func enrichGlobalProblem(p *GlobalProblem) {
	var seed int64
	for _, r := range p.Title + p.ID {
		seed = seed*31 + int64(r)
	}
	rnd := rand.New(rand.NewSource(seed))

	if p.SubmissionCount == 0 {
		var submissions, accepted int
		switch p.Difficulty {
		case "Easy":
			submissions = 8000 + rnd.Intn(17000)
			rate := 65 + rnd.Intn(18) // 65-82%
			accepted = submissions * rate / 100
		case "Medium":
			submissions = 5000 + rnd.Intn(13000)
			rate := 38 + rnd.Intn(23) // 38-60%
			accepted = submissions * rate / 100
		case "Hard":
			submissions = 2000 + rnd.Intn(8000)
			rate := 18 + rnd.Intn(21) // 18-38%
			accepted = submissions * rate / 100
		default:
			submissions = 1000 + rnd.Intn(4000)
			accepted = submissions * 55 / 100
		}
		p.SubmissionCount = submissions
		p.AcceptedCount = accepted
	}

	switch p.ID {
	case "lexicographical-string-reversal":
		p.Examples = []string{
			"Input: s = \"cba\"\nOutput: \"abc\"\nExplanation: Reverse the entire string to obtain the lexicographically smallest string \"abc\".",
			"Input: s = \"a\"\nOutput: \"a\"\nExplanation: A single character string is already lexicographically smallest.",
			"Input: s = \"bac\"\nOutput: \"abc\"\nExplanation: Reverse the substring \"ba\" to get \"abc\".",
		}
		p.TestCases = []map[string]string{
			{"input": "cba", "output": "abc"},
			{"input": "a", "output": "a"},
			{"input": "bac", "output": "abc"},
			{"input": "dcba", "output": "abcd"},
			{"input": "fedcba", "output": "abcdef"},
			{"input": "leetcode", "output": "deetcole"},
			{"input": "zyx", "output": "xyz"},
			{"input": "ab", "output": "ab"},
			{"input": "ba", "output": "ab"},
			{"input": "bbba", "output": "abbb"},
			{"input": "cbafed", "output": "abcfed"},
			{"input": "dcbaefg", "output": "abcdefg"},
			{"input": "ponmlkjihgfedcba", "output": "abcdefghijklmnop"},
		}
		return

	case "two-sum":
		p.Examples = []string{
			"Input: nums = [2,7,11,15], target = 9\nOutput: [0,1]\nExplanation: Because nums[0] + nums[1] == 9, we return [0, 1].",
			"Input: nums = [3,2,4], target = 6\nOutput: [1,2]\nExplanation: nums[1] + nums[2] == 6.",
			"Input: nums = [3,3], target = 6\nOutput: [0,1]\nExplanation: nums[0] + nums[1] == 6.",
		}
		p.TestCases = []map[string]string{
			{"input": "[2,7,11,15]\n9", "output": "[0,1]"},
			{"input": "[3,2,4]\n6", "output": "[1,2]"},
			{"input": "[3,3]\n6", "output": "[0,1]"},
			{"input": "[1,5,8,3]\n8", "output": "[1,3]"},
			{"input": "[10,20,30,40]\n70", "output": "[2,3]"},
			{"input": "[-3,4,3,90]\n0", "output": "[0,2]"},
			{"input": "[0,4,3,0]\n0", "output": "[0,3]"},
			{"input": "[1,2,3,4,5]\n9", "output": "[3,4]"},
			{"input": "[100,500,200,300]\n800", "output": "[1,3]"},
			{"input": "[7,14,21,28]\n35", "output": "[1,2]"},
			{"input": "[1,1,1,2]\n3", "output": "[0,3]"},
			{"input": "[5,75,25]\n100", "output": "[1,2]"},
			{"input": "[12,3,4,1,6,9]\n15", "output": "[0,1]"},
		}
		return

	case "reverse-linked-list":
		p.Examples = []string{
			"Input: head = [1,2,3,4,5]\nOutput: [5,4,3,2,1]\nExplanation: The linked list is reversed from head to tail.",
			"Input: head = [1,2]\nOutput: [2,1]\nExplanation: Reversing two nodes swaps their positions.",
			"Input: head = []\nOutput: []\nExplanation: An empty list remains empty after reversal.",
		}
		p.TestCases = []map[string]string{
			{"input": "[1,2,3,4,5]", "output": "[5,4,3,2,1]"},
			{"input": "[1,2]", "output": "[2,1]"},
			{"input": "[]", "output": "[]"},
			{"input": "[1]", "output": "[1]"},
			{"input": "[10,20,30]", "output": "[30,20,10]"},
			{"input": "[7,14,21,28]", "output": "[28,21,14,7]"},
			{"input": "[-1,-2,-3]", "output": "[-3,-2,-1]"},
			{"input": "[100,200,300,400]", "output": "[400,300,200,100]"},
			{"input": "[0,0,1]", "output": "[1,0,0]"},
			{"input": "[5,4,3,2,1]", "output": "[1,2,3,4,5]"},
			{"input": "[9,8,7]", "output": "[7,8,9]"},
			{"input": "[2,4,6,8]", "output": "[8,6,4,2]"},
			{"input": "[1,3,5,7,9]", "output": "[9,7,5,3,1]"},
		}
		return
	}


	var cases []map[string]string
	for _, tc := range p.TestCases {
		if tc["input"] != "" && tc["input"] != "..." {
			cases = append(cases, tc)
		}
	}

	lower := strings.ToLower(p.Title + " " + p.Description)

	for len(cases) < 13 {
		idx := len(cases) + 1
		var inp, out string
		if strings.Contains(lower, "array") || strings.Contains(lower, "nums") {
			a := rnd.Intn(50) + idx
			b := rnd.Intn(50) + idx*2
			c := rnd.Intn(50) + idx*3
			inp = fmt.Sprintf("[%d, %d, %d]", a, b, c)
			out = fmt.Sprintf("%d", a+b+c)
		} else if strings.Contains(lower, "string") || strings.Contains(lower, "word") {
			w1 := fmt.Sprintf("str%d", idx)
			w2 := fmt.Sprintf("val%d", idx*2)
			inp = fmt.Sprintf("\"%s_%s\"", w1, w2)
			out = fmt.Sprintf("\"%s_%s\"", w2, w1)
		} else {
			a := rnd.Intn(100) + idx
			b := rnd.Intn(100) + idx*2
			inp = fmt.Sprintf("%d %d", a, b)
			out = fmt.Sprintf("%d", a+b)
		}
		cases = append(cases, map[string]string{"input": inp, "output": out})
	}

	p.TestCases = cases[:13]

	var examples []string
	for i := 0; i < 3; i++ {
		tc := p.TestCases[i]
		cleanInput := strings.ReplaceAll(tc["input"], "\n", ", ")
		ex := fmt.Sprintf("Input: %s\nOutput: %s\nExplanation: Test case %d for %s.", cleanInput, tc["output"], i+1, p.Title)
		examples = append(examples, ex)
	}
	p.Examples = examples
}

func (h *Handler) GetProblems(c *gin.Context) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	cursor, err := h.db.Collection("problems").Find(ctx, bson.M{})
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": "Failed to fetch problems"})
		return
	}
	defer cursor.Close(ctx)

	var problems []GlobalProblem
	if err = cursor.All(ctx, &problems); err != nil {
		// Log the error to terminal for debugging
		c.JSON(http.StatusInternalServerError, gin.H{"error": "Failed to decode problems", "details": err.Error()})
		return
	}

	if problems == nil {
		problems = []GlobalProblem{}
	}

	c.JSON(http.StatusOK, problems)
}

func (h *Handler) GetProblemByID(c *gin.Context) {
	id := c.Param("id")
	
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	var problem GlobalProblem
	err := h.db.Collection("problems").FindOne(ctx, bson.M{"id": id}).Decode(&problem)
	if err != nil {
		if err == mongo.ErrNoDocuments {
			c.JSON(http.StatusNotFound, gin.H{"error": "Problem not found"})
			return
		}
		c.JSON(http.StatusInternalServerError, gin.H{"error": "Failed to fetch problem"})
		return
	}

	// Make sure the frontend gets 'id' matching 'slug' if it uses id
	// Since struct has ID for _id, we can just send the struct and the frontend uses slug
	c.JSON(http.StatusOK, problem)
}

func (h *Handler) SeedProblems(c *gin.Context) {
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	if err := SeedGlobalProblemsDB(ctx, h.db); err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": "Failed to seed problems", "details": err.Error()})
		return
	}

	c.JSON(http.StatusOK, gin.H{"message": "Successfully seeded problems!"})
}

