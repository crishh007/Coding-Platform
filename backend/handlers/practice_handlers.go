// SeedGlobalProblemsDB seeds the problems collection directly for CLI or startup tasks.
func SeedGlobalProblemsDB(ctx context.Context, database *mongo.Database) error {
	database.Collection("problems").Drop(ctx)

	problemsList := getInitialGlobalProblems()
	docs := make([]interface{}, len(problemsList))
	for i := range problemsList {
		enrichGlobalProblem(&problemsList[i])
		docs[i] = problemsList[i]
	}

	_, err := database.Collection("problems").InsertMany(ctx, docs)
	return err
}
